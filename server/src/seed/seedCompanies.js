/**
 * Automatically populates the company database if empty or missing records.
 */
export const seedCompaniesAuto = async () => {
  console.log("🌱 Starting safe Company database seed process...");

  for (const compData of initialCompanies) {
    const slug = compData.slug || compData.companyName.toLowerCase().replace(/[^a-z0-9]+/g, "-");
    await Company.findOneAndUpdate(
      { companyName: compData.companyName },
      { ...compData, slug },
      { upsert: true, new: true, runValidators: true }
    );
  }

  const count = await Company.countDocuments();
  console.log(`✅ Company database seed complete! Total Companies in DB: ${count}`);
  return count;
};

// Executable script when called directly via CLI
if (process.argv[1]?.includes("seedCompanies.js")) {
  const mongoUri = process.env.MONGODB_URI || "mongodb://127.0.0.1:27017/careeros";
  mongoose
    .connect(mongoUri)
    .then(async () => {
      await seedCompaniesAuto();
      process.exit(0);
    })
    .catch((err) => {
      console.error("Seed error:", err);
      process.exit(1);
    });
}
